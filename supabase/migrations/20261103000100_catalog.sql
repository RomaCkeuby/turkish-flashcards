-- Additive pilot schema. No production data or credentials are included.
create schema if not exists private;
revoke all on schema private from public, anon, authenticated;

create table public.profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  time_zone text not null default 'Europe/Moscow',
  created_at timestamptz not null default now()
);
create table private.collection_roles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  role text not null check (role = 'owner')
);
create function private.require_user() returns uuid language plpgsql stable
set search_path = '' as $$
declare u uuid := auth.uid();
begin
  if u is null then raise exception 'Authentication required' using errcode = '42501'; end if;
  return u;
end $$;
create function private.create_profile() returns trigger language plpgsql security definer
set search_path = '' as $$ begin
  insert into public.profiles(user_id) values(new.id) on conflict do nothing;
  return new;
end $$;
create trigger create_flashcards_profile after insert on auth.users
for each row execute function private.create_profile();
insert into public.profiles(user_id) select id from auth.users on conflict do nothing;

create table public.sources (
  id bigint generated by default as identity primary key check (id between 1 and 9007199254740991),
  source_key text not null unique, name text not null, version text not null,
  license text not null, url text, updated_at timestamptz not null
);
create table public.entries (
  id bigint generated by default as identity primary key check (id between 1 and 9007199254740991),
  source_id bigint not null references public.sources,
  source_key text not null, turkish text not null, russian text not null,
  example_turkish text not null default '', example_russian text not null default '',
  example_source text not null default '', example_source_license text not null default '',
  example_source_url text not null default '', example_translation_source_url text not null default '',
  part_of_speech text not null, category text not null, active integer not null default 1 check(active in (0,1)),
  created_at timestamptz not null, updated_at timestamptz not null,
  unique(source_id, source_key)
);
create table public.cards (
  id bigint generated by default as identity primary key check (id between 1 and 9007199254740991),
  entry_id bigint not null references public.entries on delete cascade,
  direction text not null check(direction in ('tr-ru','ru-tr')),
  enabled integer not null default 1 check(enabled in (0,1)), unique(entry_id, direction)
);
create table public.entry_overrides (
  entry_id bigint primary key references public.entries on delete cascade,
  turkish text, russian text, part_of_speech text, category text,
  status text check(status in ('ACTIVE','ARCHIVED','DISABLED')),
  tags_overridden integer not null default 0 check(tags_overridden in (0,1)), updated_at timestamptz not null
);
create table public.entry_translation_items (
  id bigint generated by default as identity primary key,
  entry_id bigint not null references public.entries on delete cascade,
  layer text not null check(layer in ('base','override')), text text not null,
  is_primary integer not null default 0 check(is_primary in (0,1)), position integer not null default 0,
  source_name text not null default '', source_url text not null default '', source_license text not null default '',
  created_at timestamptz not null, updated_at timestamptz not null, unique(entry_id,layer,position)
);
create table public.entry_example_items (
  id bigint generated by default as identity primary key,
  entry_id bigint not null references public.entries on delete cascade,
  layer text not null check(layer in ('base','override')), turkish text not null, russian text not null,
  is_primary integer not null default 0 check(is_primary in (0,1)), position integer not null default 0,
  source_name text not null default '', source_url text not null default '', source_license text not null default '',
  created_at timestamptz not null, updated_at timestamptz not null, unique(entry_id,layer,position)
);
create table public.entry_tags (
  id bigint generated by default as identity primary key,
  entry_id bigint not null references public.entries on delete cascade,
  layer text not null check(layer in ('base','override')), tag text not null, created_at timestamptz not null,
  unique(entry_id,layer,tag)
);
create table public.entry_change_log (
  id bigint generated by default as identity primary key,
  entry_id bigint not null references public.entries on delete cascade,
  field text not null, old_value_json text not null, new_value_json text not null,
  change_source text not null check(change_source in ('user','update','rollback')), changed_at timestamptz not null
);
create table public.entry_removals (
  entry_id bigint primary key references public.entries on delete cascade,
  kind text not null check(kind in ('deleted','merged')),
  target_id bigint references public.entries, removed_at timestamptz not null,
  check((kind = 'deleted' and target_id is null) or (kind = 'merged' and target_id is not null and target_id <> entry_id))
);
create table public.review_state (
  user_id uuid not null references auth.users on delete cascade,
  card_id bigint not null references public.cards on delete cascade,
  due_at timestamptz not null, interval_days double precision not null check(interval_days >= 0),
  ease_factor double precision not null check(ease_factor between 1.3 and 3),
  repetitions integer not null check(repetitions >= 0), lapses integer not null check(lapses >= 0),
  first_reviewed_at timestamptz, last_reviewed_at timestamptz,
  primary key(user_id, card_id)
);
create table public.review_log (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users on delete cascade,
  card_id bigint not null references public.cards on delete cascade,
  rating text not null check(rating in ('again','hard','good','easy')), reviewed_at timestamptz not null,
  request_id uuid, unique(user_id,request_id)
);
create table private.review_requests (
  user_id uuid not null references auth.users on delete cascade, request_id uuid not null,
  card_id bigint not null references public.cards, result text not null check(result in ('correct','incorrect')),
  response jsonb not null, created_at timestamptz not null default now(), primary key(user_id,request_id)
);
create table private.review_undo (
  user_id uuid primary key references auth.users on delete cascade,
  token uuid not null unique, review_log_id bigint not null references public.review_log on delete cascade,
  previous_state jsonb, result_state jsonb not null
);
create table private.update_history (
  id bigint generated by default as identity primary key,
  package_version text not null, manifest_sha256 text not null, applied_at timestamptz not null,
  added_count integer not null, changed_count integer not null, disabled_count integer not null
);
create table private.update_snapshots (
  id bigint generated by default as identity primary key,
  package_version text not null, manifest_sha256 text not null, snapshot_json text not null, created_at timestamptz not null
);
create table private.app_settings (key text primary key, value text not null, updated_at timestamptz not null);
create table private.migration_imports (
  snapshot_id text primary key check(snapshot_id ~ '^[a-f0-9]{64}$'),
  owner_id uuid not null references auth.users, imported_at timestamptz not null default now(),
  report jsonb not null
);
create index entries_category_idx on public.entries(category);
create index cards_entry_idx on public.cards(entry_id);
create index review_state_due_idx on public.review_state(user_id,due_at);
create index review_log_day_idx on public.review_log(user_id,reviewed_at);
create index entry_history_idx on public.entry_change_log(entry_id,changed_at);

-- Do not expose roles, snapshots, undo snapshots or request receipts through Data API.
do $$ declare t text; begin
  foreach t in array array['profiles','sources','entries','cards','entry_overrides','entry_translation_items',
    'entry_example_items','entry_tags','entry_change_log','entry_removals','review_state','review_log'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('revoke all on public.%I from public, anon, authenticated', t);
    execute format('grant select on public.%I to authenticated', t);
    if t in ('profiles','review_state','review_log') then
      execute format('create policy self_read on public.%I for select to authenticated using (user_id = (select auth.uid()))',t);
    else
      execute format('create policy catalog_read on public.%I for select to authenticated using ((select auth.uid()) is not null)',t);
    end if;
  end loop;
  foreach t in array array['collection_roles','review_requests','review_undo','update_history','update_snapshots','app_settings','migration_imports'] loop
    execute format('alter table private.%I enable row level security',t);
    execute format('revoke all on private.%I from public, anon, authenticated',t);
  end loop;
end $$;
