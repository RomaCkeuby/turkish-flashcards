-- View remains subject to the caller's RLS. Empty overrides must survive COALESCE.
create view public.effective_entries with (security_invoker = true) as
select e.id, e.active, e.source_id, e.source_key,
  coalesce(o.turkish,e.turkish) turkish, coalesce(o.russian,e.russian) russian,
  coalesce(o.part_of_speech,e.part_of_speech) part_of_speech, coalesce(o.category,e.category) category,
  coalesce(o.status,case when e.active=1 then 'ACTIVE' else 'DISABLED' end) status,
  e.created_at, coalesce(o.updated_at,e.updated_at) updated_at,
  coalesce(x.turkish,e.example_turkish) example_turkish, coalesce(x.russian,e.example_russian) example_russian,
  coalesce(x.source_name,e.example_source) example_source, coalesce(x.source_license,e.example_source_license) example_source_license,
  coalesce(x.source_url,e.example_source_url) example_source_url,
  case when x.id is null then e.example_translation_source_url else '' end example_translation_source_url,
  s.name source_name, s.license source_license, s.url source_url,
  coalesce((select array_agg(t.tag order by t.tag) from public.entry_tags t where t.entry_id=e.id
    and t.layer=case when coalesce(o.tags_overridden,0)=1 then 'override' else 'base' end),array[]::text[]) tags,
  r.kind removal_kind
from public.entries e join public.sources s on s.id=e.source_id
left join public.entry_overrides o on o.entry_id=e.id
left join public.entry_removals r on r.entry_id=e.id
left join lateral (select * from public.entry_example_items i where i.entry_id=e.id and i.layer='override' and i.is_primary=1
  order by i.position,i.id limit 1) x on true;
revoke all on public.effective_entries from public, anon, authenticated;
grant select on public.effective_entries to authenticated;
